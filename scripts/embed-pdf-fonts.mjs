import { readFile, writeFile } from "node:fs/promises";
import { resolve } from "node:path";

const [regularPath, boldPath] = process.argv.slice(2);
if (!regularPath || !boldPath) {
  throw new Error("Usage: node scripts/embed-pdf-fonts.mjs <regular.ttf> <bold.ttf>");
}

const [regular, bold] = await Promise.all([readFile(resolve(regularPath)), readFile(resolve(boldPath))]);
const source = `// Generated by scripts/embed-pdf-fonts.mjs. Do not edit by hand.\n` +
  `const decode = (value: string): Uint8Array => Uint8Array.from(atob(value), (character) => character.charCodeAt(0));\n\n` +
  `export const WORKSBIEN_SANS_REGULAR = decode("${regular.toString("base64")}");\n` +
  `export const WORKSBIEN_SANS_BOLD = decode("${bold.toString("base64")}");\n`;

await writeFile(new URL("../src/pdf-font-assets.ts", import.meta.url), source, "utf8");
